import { readFile, writeFile, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const { version } = pkg;
await writeFile(
  'src/version.ts',
  `// Generated from package.json by scripts/build.mjs.\nexport const version = ${JSON.stringify(version)};\n`,
);
await rm('dist', { recursive: true, force: true });
execFileSync(process.execPath, ['node_modules/typescript/bin/tsc'], {
  stdio: 'inherit',
});
// Paperclip 2026.1005.0 caches manifest imports by path and mtime. npm packs
// normalize mtimes, and cache busting a parent does not refresh its imports.
// Give each release its own entrypoint with the entire manifest inlined.
const manifestJson = execFileSync(
  process.execPath,
  [
    '--input-type=module',
    '-e',
    "import manifest from './dist/manifest.js'; process.stdout.write(JSON.stringify(manifest));",
  ],
  { encoding: 'utf8' },
);
const manifestPath = `dist/manifest-${version}.js`;
await writeFile(
  manifestPath,
  `// Generated by scripts/build.mjs for Paperclip's manifest loader.\nexport default ${manifestJson};\n`,
);
pkg.paperclipPlugin.manifest = manifestPath;
await writeFile('package.json', `${JSON.stringify(pkg, null, 2)}\n`);
